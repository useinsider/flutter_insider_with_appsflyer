/// Position values accepted by
/// [FlutterInsider.setInternalBrowserCloseButtonPosition].
///
/// Controls where the close (X) button is rendered inside the Insider
/// internal browser.
class InsiderCloseButtonPosition {
  /// Render the close button in the top-left corner.
  final String LEFT = "LEFT";

  /// Render the close button in the top-right corner.
  final String RIGHT = "RIGHT";

  /// Hide the close button entirely.
  final String NONE = "NONE";
}
